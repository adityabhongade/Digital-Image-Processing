%% Experiment 8 : Edge Detection

clc; close all; clear;

%% Prewitt Operators

I = im2double(imread('circuit.tif'));

% Masks
maskGx = [-1 -1 -1; 0 0 0; 1 1 1];
maskGy = [-1 0 1; -1 0 1; -1 0 1];

Gx = imfilter(I, maskGx,'same');
Gy = imfilter(I, maskGy, 'same');

F = abs(Gx) + abs(Gy);

figure,
subplot(2, 2, 1), imshow(I), title("Original Image");
subplot(2, 2, 2), imshow(F), title("Edge Detected");
subplot(2, 2, 3), imshow(Gx), title("Horizontal Edges");
subplot(2, 2, 4), imshow(Gy), title("Vertical Edges");

%% Sobel Operators

I = im2double(imread('Images10/house.tif'));
% Masks
G45pMask = [0 1 2; -1 0 1; -2 -1 0];
G45nMask = [-2 -1 0; -1 0 1; 0 1 2];

Ga = imfilter(I, G45pMask, 'same');
Gb = imfilter(I, G45nMask, 'same');

G = abs(Ga) + abs(Gb);

figure,
subplot(2, 2, 1), imshow(I), title("Original Image");
subplot(2, 2, 2), imshow(G), title("Edge Detected");
subplot(2, 2, 3), imshow(Ga), title("+45 Edges");
subplot(2, 2, 4), imshow(Gb), title("-45 Edges");

